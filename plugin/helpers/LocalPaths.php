/**
 * Local working directories for SharePoint backups and remote restores.
 *
 * They live under uploads/spsync-backups/<random token>/ so artifact URLs cannot be guessed
 * from the timestamped backup ID. Deny rules are written for Apache 2.2/2.4 and IIS; Nginx
 * ignores them, which is why the unguessable token matters (see README for an Nginx rule).
 */
class LocalPaths
{
    public static function base()
    {
        $upload_dir = wp_upload_dir();
        return rtrim(str_replace('\\', '/', $upload_dir['basedir']), '/') . '/spsync-backups';
    }

    /** Per-installation random directory; created and protected on first use. */
    public static function private_root()
    {
        $token = Settings::get('local_storage_token', '');
        if (!is_string($token) || !preg_match('/\A[a-f0-9]{32}\z/D', $token)) {
            $token = bin2hex(random_bytes(16));
            Settings::set('local_storage_token', $token);
        }
        $root = self::base() . '/' . $token;
        if (!is_dir($root)) {
            wp_mkdir_p($root);
        }
        self::protect(self::base());
        self::protect($root);
        return $root;
    }

    public static function backup_dir($backup_id)
    {
        return self::private_root() . '/' . $backup_id;
    }

    /** Pre-1.4.0 location, still read so uploads queued before an upgrade complete. */
    public static function legacy_backup_dir($backup_id)
    {
        return self::base() . '/' . $backup_id;
    }

    /**
     * Delete the local working copy of one backup (current and pre-1.4.0 locations).
     *
     * @return bool True if a directory was removed.
     */
    public static function remove_backup($backup_id)
    {
        if (!is_string($backup_id) || !preg_match('/\Aspsync-backup-[A-Za-z0-9_-]{1,80}\z/D', $backup_id)) {
            return false;
        }
        $removed = false;
        foreach ([self::backup_dir($backup_id), self::legacy_backup_dir($backup_id)] as $dir) {
            if (!is_dir($dir) || is_link($dir)) {
                continue;
            }
            // Backups are flat: archive parts, database.sql, manifest.json and the protection files.
            foreach ((array) @scandir($dir) as $name) {
                $file = $dir . '/' . $name;
                if ($name !== '.' && $name !== '..' && (is_file($file) || is_link($file))) {
                    @unlink($file);
                }
            }
            $removed = @rmdir($dir) || $removed;
        }
        return $removed;
    }

    public static function restore_dir()
    {
        return self::private_root() . '/restore';
    }

    public static function rollback_dir()
    {
        return self::private_root() . '/rollback';
    }

    /** Best-effort web-access denial for Apache (2.2 and 2.4) and IIS, plus an index guard. */
    public static function protect($dir)
    {
        if (!is_dir($dir)) {
            return;
        }
        $files = [
            '.htaccess'  => "# Generated by WordPress SharePoint Backup Plugin\n" .
                "<IfModule mod_authz_core.c>\n    Require all denied\n</IfModule>\n" .
                "<IfModule !mod_authz_core.c>\n    Order deny,allow\n    Deny from all\n</IfModule>\n" .
                "Options -Indexes\n",
            'web.config' => "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<configuration>\n  <system.webServer>\n" .
                "    <authorization>\n      <deny users=\"*\" />\n    </authorization>\n" .
                "    <directoryBrowse enabled=\"false\" />\n  </system.webServer>\n</configuration>\n",
            'index.php'  => "<?php // Silence is golden\n",
        ];
        foreach ($files as $name => $contents) {
            $path = $dir . '/' . $name;
            // Upgrade the old "Deny from all"-only .htaccess, which breaks or is ignored on Apache 2.4.
            if (!file_exists($path) || ($name === '.htaccess' && strpos((string) @file_get_contents($path), 'Require all denied') === false)) {
                @file_put_contents($path, $contents);
            }
        }
    }
}
